import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import {
  type DatasetLock,
  diffTasks,
  ensureGitignore,
  formatLock,
  readLock,
  readState,
  sameTasks,
  writeLock,
  writeState,
} from "./lockfile";

const h = (c: string) => `sha256:${c.repeat(64)}`;

let root: string;

beforeEach(async () => {
  root = await mkdtemp(path.join(tmpdir(), "lmnr-lock-"));
});

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

void describe("lmnr.lock", () => {
  void it("writes keys in order, tasks sorted, and reads it back", async () => {
    const lock: DatasetLock = {
      dataset: "support",
      version: 7,
      tasks: { "refund-partial": h("b"), "10": h("c"), "2": h("d"), a: h("a") },
    };
    await writeLock(root, lock);

    const text = await readFile(path.join(root, "lmnr.lock"), "utf8");
    expect(text).toBe(
      "# Generated by lmnr-cli (eval push / eval pull). Commit it; don't edit by hand.\n" +
        "dataset: support\n" +
        "version: 7\n" +
        "tasks:\n" +
        `  "10": ${h("c")}\n` +
        `  "2": ${h("d")}\n` +
        `  a: ${h("a")}\n` +
        `  refund-partial: ${h("b")}\n`,
    );
    expect(await readLock(root)).toEqual(lock);
  });

  void it("round-trips names YAML would read as other types", async () => {
    const lock: DatasetLock = {
      dataset: "123",
      version: 1,
      tasks: { true: h("a"), null: h("b"), "1e5": h("c"), "0.5": h("d") },
    };
    await writeLock(root, lock);
    expect(await readLock(root)).toEqual(lock);
    expect(formatLock({ ...lock, tasks: {} })).toMatch(/tasks: {}\n$/);
  });

  void it("is absent without a file and rejected when malformed", async () => {
    expect(await readLock(root)).toBeNull();
    for (const bad of [
      "dataset: s\nversion: 0\ntasks: {}\n",
      "dataset: s\nversion: 1\ntasks: {a: sha256:nope}\n",
      "version: 1\ntasks: {}\n",
      "- a\n",
      "dataset: [\n",
    ]) {
      await writeFile(path.join(root, "lmnr.lock"), bad);
      await expect(readLock(root)).rejects.toMatchObject({
        code: "invalid_evals_dir",
        message: expect.stringMatching(/is not a valid lockfile/),
      });
    }
  });
});

void describe(".lmnr-state.json", () => {
  void it("round-trips, and an unreadable one counts as unknown", async () => {
    await mkdir(path.join(root, "tasks"));
    const state = { dataset: "s", version: 2, tasks: { a: h("a") } };
    await writeState(root, state);
    expect(await readState(root)).toEqual(state);
    await writeFile(path.join(root, "tasks/.lmnr-state.json"), "{oops");
    expect(await readState(root)).toBeNull();
  });
});

void describe("ensureGitignore", () => {
  void it("adds /tasks/ once, keeping what's there", async () => {
    expect(await ensureGitignore(root)).toBe(true);
    expect(await readFile(path.join(root, ".gitignore"), "utf8")).toBe(
      "/tasks/\n",
    );
    expect(await ensureGitignore(root)).toBe(false);

    await writeFile(path.join(root, ".gitignore"), "jobs/");
    expect(await ensureGitignore(root)).toBe(true);
    expect(await readFile(path.join(root, ".gitignore"), "utf8")).toBe(
      "jobs/\n/tasks/\n",
    );

    for (const existing of ["tasks", "tasks/", "/tasks", " /tasks/ "]) {
      await writeFile(path.join(root, ".gitignore"), `x\n${existing}\r\n`);
      expect(await ensureGitignore(root)).toBe(false);
    }
  });
});

void describe("task diffs", () => {
  void it("compares task maps", () => {
    const from = { a: h("a"), b: h("b"), c: h("c") };
    const to = { b: h("b"), c: h("d"), d: h("d") };
    expect(diffTasks(from, to)).toEqual({
      added: ["d"],
      modified: ["c"],
      removed: ["a"],
    });
    expect(sameTasks(from, { ...from })).toBe(true);
    expect(sameTasks(from, to)).toBe(false);
    expect(sameTasks({}, {})).toBe(true);
    expect(sameTasks({ a: h("a") }, { b: h("a") })).toBe(false);
  });
});
